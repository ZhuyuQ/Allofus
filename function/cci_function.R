    group_by(cohort, person_id) %>%
    summarise(cci_score = sum(weight), .groups = "drop") %>%
    # ── Add CCI = 0 for patients with no matching conditions ─────────────────
    right_join(df %>% distinct(cohort, person_id), by = c("cohort", "person_id")) %>%
    mutate(cci_score = replace_na(cci_score, 0)) %>%
    # ── Add age points safely ────────────────────────────────────────────────
    left_join(age_lookup, by = c("cohort", "person_id")) %>%
    mutate(cci_score = cci_score + age_points) %>%
    select(-age, -age_points)
  return(cci_scores)
}
